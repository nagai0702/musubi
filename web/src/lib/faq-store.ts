/* ===== 学習済み辞書の読み込み（インライン） ===== */

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

function applyLearnedCorrectionsInline(text: string): string {
  try {
    const dictPath = join(process.cwd(), 'data', 'learned-corrections.json');
    if (!existsSync(dictPath)) {
      console.log('[FAQ] 辞書ファイルなし:', dictPath);
      return text;
    }
    const raw = readFileSync(dictPath, 'utf-8');
    const corrections = JSON.parse(raw) as { wrong: string; correct: string }[];
    let result = text;
    for (const c of corrections) {
      if (result.includes(c.wrong)) {
        result = result.replaceAll(c.wrong, c.correct);
        console.log('[FAQ] 学習補正:', c.wrong, '→', c.correct);
      }
    }
    return result;
  } catch (e: any) {
    console.error('[FAQ] 辞書読み込みエラー:', e.message);
    return text;
  }
}

