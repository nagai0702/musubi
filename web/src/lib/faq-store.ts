function correctMisrecognition(text: string): string {
  let corrected = text;
  for (const [pattern, replacement] of MISRECOGNITION_MAP) {
    corrected = corrected.replace(pattern, replacement);
  }
  return corrected;
}

export async function searchFAQ(query: string, topK = 3): Promise<FAQResult[]> {
  ensureInit();

  // 1. ハードコード辞書で補正
  let corrected = correctMisrecognition(query);

  // 2. 学習済み辞書でさらに補正
  corrected = applyLearnedCorrectionsInline(corrected);

  // 元のクエリと補正後の両方で検索し、スコアが高い方を採用
  const results1 = keywordSearch(query, topK * 2);
  const results2 = corrected !== query ? keywordSearch(corrected, topK * 2) : [];

  // 重複排除しつつマージ
  const seen = new Set<string>();
  const merged: FAQResult[] = [];
  for (const r of [...results1, ...results2].sort((a,b) => b.score - a.score)) {
    if (!seen.has(r.question)) {
      seen.add(r.question);
      merged.push(r);
    }
  }

  return merged.slice(0, topK);
}

function keywordSearch(query: string, topK: number): FAQResult[] {
  const q = query;

  // クエリを分割（助詞・接続詞でも分割）
  const words = q.split(/[\s。、？?！!「」（）\sってはがをのにでもとかからまでよりけどだけしてくれるなるする]+/).filter(w => w.length >= 2);

  // 重要な1-2文字キーワードも追加
  const extraKeywords: string[] = [];
  const importantChars = ['料金','費用','分割','返金','退会','休会','写真','面談','紹介','お泊','交際','成婚','入会','書類','年齢','地方','特典','割引','ローン'];
  for (const kw of importantChars) {
    if (q.includes(kw)) extraKeywords.push(kw);
  }

  const allWords = [...new Set([...words, ...extraKeywords])];

  const scored = faqItems.map(f => {
    let score = 0;

    for (const word of allWords) {
      // 質問文にマッチ → 高得点
      if (f.question.includes(word)) score += 10;
      // 回答にマッチ
      if (f.answer.includes(word)) score += 3;
      // aliases にマッチ → 高得点（これが肝）
      for (const alias of f.aliases) {
        if (alias === word) score += 15;           // 完全一致
        else if (word.includes(alias)) score += 10; // wordがaliasを含む
        else if (alias.includes(word)) score += 8;  // aliasがwordを含む
      }
    }

    // クエリ全体にaliasが含まれる（最も強いマッチ）
    for (const alias of f.aliases) {
      if (q.includes(alias) && alias.length >= 3) score += 15;
    }

    return { question: f.question, answer: f.answer, category: f.category, score };
  })
  .filter(f => f.score > 0)
  .sort((a, b) => b.score - a.score);

  return scored.slice(0, topK);
}
